const assert=require('node:assert/strict');
const V=require('./candidate.cjs');
const p={school_id:'cysh',role:'student'};
const item={school:'cysh',category:'升學',published_date:'2026-09-24',title:'資訊'};
assert.equal(V.date('2026-02-30'),null);
assert.throws(()=>V.score(item,p,'2026-02-30'));
assert.equal(V.features({...item,source_observation:{http_status:404}},'2026-09-25').confirmedMissing,true);
assert.equal(V.score({...item,source_observation:{http_status:404}},p,'2026-09-25',{availability:true}).eligible,false);
assert.equal(V.score({...item,source_observation:{fetch_failed:true}},p,'2026-09-25',{availability:true}).eligible,true);
assert.equal(V.features({...item,title:'學生競賽及教師研習'},'2026-09-25').audience.teacher_only,false);
assert.equal(V.score({...item,title:'教師研習'},p,'2026-09-25',{audience:true}).eligible,false);
assert.equal(V.score({...item,title:'教師研習'},{...p,role:'teacher'},'2026-09-25',{audience:true}).eligible,true);
assert.equal(V.score({...item,title:'學生競賽及教師研習'},p,'2026-09-25',{audience:true}).eligible,true);
assert.equal(V.features({...item,title:'116學年度招生資料'},'2026-09-25').dates.length,0);
assert.equal(V.temporalDates('報名至114年6月6日止')[0].date,'2025-06-06');
assert.equal(V.score({...item,title:'報名至114年6月6日止'},p,'2026-09-25',{temporal:true}).eligible,false);
assert.equal(V.score({...item,title:'使用規範'},p,'2026-09-25',{ageLongLived:true}).eligible,false);
assert.equal(V.score({...item,title:'使用規範：請於2026年9月30日前申請'},p,'2026-09-25',{ageLongLived:true}).eligible,true);
assert.deepEqual(V.score(item,p,'2026-09-25'),V.score({...item,human_label:'must_show',teacher_related:true,announcement_missing:true,machine_label:'useful'},p,'2026-09-25'));
const discovered={...item,published_date:null,first_seen_date:'2026-09-24'};
assert(V.score(discovered,p,'2026-09-25',{ageLongLived:true}).score<V.score(discovered,p,'2026-09-25').score);
const oldAction={...item,published_date:'2025-01-01',title:'報名至2026年9月30日止'};
assert.equal(V.score(oldAction,p,'2026-09-25',{ageLongLived:true}).eligible,true);
assert(V.score(oldAction,p,'2026-09-25',{ageLongLived:true}).score>V.score(oldAction,p,'2026-09-25').score);
console.log('PASS: feature, policy, role, strict date, age interaction and answer-leakage assertions');
