-- Announcement email digest V1.
-- Users opt in through user_preferences.preferences.notification_preferences.email.
-- Only approved accounts with the "notifications" capability are eligible.
-- Delivery state is backend-only; browsers can never read or write it.

create table if not exists private.announcement_email_digests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  frequency text not null check (frequency in ('instant', 'daily')),
  item_count integer not null check (item_count between 1 and 50),
  sent_at timestamptz not null default now()
);
create index if not exists announcement_email_digests_sent_at_idx
  on private.announcement_email_digests (sent_at);
create index if not exists announcement_email_digests_user_sent_idx
  on private.announcement_email_digests (user_id, sent_at desc);

create table if not exists private.announcement_email_deliveries (
  user_id uuid not null references auth.users(id) on delete cascade,
  announcement_id text not null check (char_length(announcement_id) between 1 and 180),
  digest_id bigint not null references private.announcement_email_digests(id) on delete cascade,
  primary key (user_id, announcement_id)
);

revoke all on table private.announcement_email_digests from public, anon, authenticated;
revoke all on table private.announcement_email_deliveries from public, anon, authenticated;

-- Eligible recipients with their keywords and the announcement IDs already mailed
-- in the last 14 days (enough to cover the worker's 3-day lookback window).
create or replace function public.email_digest_recipients()
returns table(
  user_id uuid,
  email text,
  frequency text,
  enabled_at timestamptz,
  keywords jsonb,
  sent_ids text[],
  last_sent_at timestamptz
)
language sql
stable
security definer
set search_path = pg_catalog, public, private
as $$
  with opted as (
    select p.user_id,
           p.preferences #> '{notification_preferences,email}' as email_pref,
           p.preferences #> '{profile,tracked_keywords}' as profile_keywords
    from public.user_preferences p
    where coalesce((p.preferences #>> '{notification_preferences,email,enabled}')::boolean, false)
  )
  select o.user_id,
         lower(u.email)::text,
         case when o.email_pref ->> 'frequency' = 'instant' then 'instant' else 'daily' end,
         coalesce(
           case when (o.email_pref ->> 'enabled_at') ~ '^\d{4}-\d{2}-\d{2}T'
                then (o.email_pref ->> 'enabled_at')::timestamptz end,
           now()
         ),
         coalesce((
           select jsonb_agg(distinct k.keyword)
           from (
             select s.keyword from public.user_subscriptions s
             where s.user_id = o.user_id and s.deleted_at is null
             union
             select trim(value) from jsonb_array_elements_text(
               case when jsonb_typeof(o.profile_keywords) = 'array' then o.profile_keywords else '[]'::jsonb end
             ) value
           ) k
           where length(trim(k.keyword)) > 0
         ), '[]'::jsonb),
         coalesce((
           select array_agg(d.announcement_id)
           from private.announcement_email_deliveries d
           join private.announcement_email_digests g on g.id = d.digest_id
           where d.user_id = o.user_id and g.sent_at > now() - interval '14 days'
         ), array[]::text[]),
         (select max(g.sent_at) from private.announcement_email_digests g where g.user_id = o.user_id)
  from opted o
  join auth.users u on u.id = o.user_id
  join public.account_access a on a.user_id = o.user_id and a.status = 'approved'
  join public.account_capabilities c on c.user_id = o.user_id
       and c.capability = 'notifications' and c.enabled
  where u.email is not null and u.email_confirmed_at is not null
$$;

-- Number of digest emails sent since a timestamp (used for the provider's daily quota).
create or replace function public.email_digest_sent_since(since timestamptz)
returns integer
language sql
stable
security definer
set search_path = pg_catalog, private
as $$
  select count(*)::integer from private.announcement_email_digests where sent_at >= since
$$;

-- Record one delivered digest and its announcements atomically.
create or replace function public.record_email_digest(
  target_user_id uuid,
  digest_frequency text,
  announcement_ids text[]
)
returns bigint
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
declare new_id bigint;
begin
  if announcement_ids is null or cardinality(announcement_ids) not between 1 and 50 then
    raise exception 'invalid_digest_items' using errcode = '22023';
  end if;
  insert into private.announcement_email_digests (user_id, frequency, item_count)
  values (target_user_id, digest_frequency, cardinality(announcement_ids))
  returning id into new_id;
  insert into private.announcement_email_deliveries (user_id, announcement_id, digest_id)
  select target_user_id, item, new_id from unnest(announcement_ids) item
  on conflict (user_id, announcement_id) do nothing;
  return new_id;
end;
$$;

-- One-click unsubscribe (the worker verifies an HMAC token before calling this).
create or replace function public.email_digest_unsubscribe(target_user_id uuid)
returns void
language sql
security definer
set search_path = pg_catalog, public
as $$
  update public.user_preferences
  set preferences = jsonb_set(
        preferences,
        '{notification_preferences,email,enabled}',
        'false'::jsonb,
        true
      ),
      updated_at = now()
  where user_id = target_user_id
    and preferences #> '{notification_preferences,email}' is not null
$$;

revoke all on function public.email_digest_recipients() from public, anon, authenticated;
revoke all on function public.email_digest_sent_since(timestamptz) from public, anon, authenticated;
revoke all on function public.record_email_digest(uuid, text, text[]) from public, anon, authenticated;
revoke all on function public.email_digest_unsubscribe(uuid) from public, anon, authenticated;
grant execute on function public.email_digest_recipients() to service_role;
grant execute on function public.email_digest_sent_since(timestamptz) to service_role;
grant execute on function public.record_email_digest(uuid, text, text[]) to service_role;
grant execute on function public.email_digest_unsubscribe(uuid) to service_role;
