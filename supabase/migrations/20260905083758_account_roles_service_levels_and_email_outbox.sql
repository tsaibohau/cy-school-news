-- Scalable account administration with explicit owner/co-admin boundaries,
-- service levels, re-application, and a server-only email delivery outbox.

alter table public.app_admins
  add column if not exists admin_role text not null default 'co_admin'
  check (admin_role in ('owner', 'co_admin'));

update public.app_admins
set admin_role = 'owner'
where user_id = (
  select user_id from public.app_admins
  where revoked_at is null
  order by created_at asc, user_id asc
  limit 1
)
and not exists (
  select 1 from public.app_admins where admin_role = 'owner' and revoked_at is null
);

create unique index if not exists app_admins_one_active_owner
  on public.app_admins ((admin_role))
  where admin_role = 'owner' and revoked_at is null;

alter table public.account_access
  add column if not exists service_level text not null default 'full'
  check (service_level in ('full', 'timetable_only')),
  add column if not exists last_reapplied_at timestamptz;

alter table public.admin_audit_log
  drop constraint if exists admin_audit_log_action_check;
alter table public.admin_audit_log
  add constraint admin_audit_log_action_check check (action in (
    'invite_requested', 'account_approved', 'account_rejected',
    'access_reapplied', 'service_changed', 'coadmin_granted', 'coadmin_revoked'
  ));

create table if not exists private.account_email_outbox (
  id bigint generated by default as identity primary key,
  event_key text not null unique,
  recipient_email text not null,
  template text not null check (template in (
    'registration_notice', 'access_approved', 'access_rejected',
    'access_reapplied', 'service_changed', 'coadmin_granted', 'coadmin_revoked'
  )),
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  claimed_at timestamptz,
  sent_at timestamptz,
  attempts integer not null default 0,
  last_error text
);

revoke all on table private.account_email_outbox from public, anon, authenticated;

create or replace function private.queue_account_email(
  event_key text,
  recipient_email text,
  template text,
  payload jsonb default '{}'::jsonb
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
begin
  if event_key is null or length(event_key) > 180 then
    raise exception 'invalid email event key' using errcode = '22023';
  end if;
  if recipient_email is null or length(recipient_email) > 254 then
    raise exception 'invalid email recipient' using errcode = '22023';
  end if;
  insert into private.account_email_outbox (event_key, recipient_email, template, payload)
  values (event_key, lower(recipient_email), template, coalesce(payload, '{}'::jsonb))
  on conflict (event_key) do nothing;
end;
$$;

revoke all on function private.queue_account_email(text, text, text, jsonb) from public, anon, authenticated;

