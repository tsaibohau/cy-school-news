create function public.current_account_access()
returns table(status text, is_admin boolean, admin_role text, service_level text, can_reapply boolean)
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
begin
  if auth.uid() is null then
    raise exception 'authenticated user required' using errcode = '28000';
  end if;
  return query
    select
      coalesce(access.status, 'pending')::text,
      (admin.user_id is not null),
      admin.admin_role::text,
      coalesce(access.service_level, 'full')::text,
      (coalesce(access.status, 'pending') = 'rejected')
    from (select 1) seed
    left join public.account_access access on access.user_id = auth.uid()
    left join public.app_admins admin on admin.user_id = auth.uid() and admin.revoked_at is null;
end;
$$;

