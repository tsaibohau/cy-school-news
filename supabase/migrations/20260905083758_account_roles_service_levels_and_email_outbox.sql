-- Service-role-only queue API used by the email Edge Function.
create or replace function public.claim_account_email_outbox(batch_size integer default 20)
returns table(id bigint, recipient_email text, template text, payload jsonb)
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
begin
  return query
  with claimed as (
    select outbox.id
    from private.account_email_outbox outbox
    where outbox.sent_at is null
      and outbox.attempts < 5
      and (outbox.claimed_at is null or outbox.claimed_at < now() - interval '10 minutes')
    order by outbox.created_at asc
    limit least(greatest(coalesce(batch_size, 20), 1), 50)
    for update skip locked
  )
  update private.account_email_outbox outbox
  set claimed_at = now(), attempts = attempts + 1
  from claimed
  where outbox.id = claimed.id
  returning outbox.id, outbox.recipient_email, outbox.template, outbox.payload;
end;
$$;

create or replace function public.finish_account_email_outbox(message_id bigint, delivered boolean, failure text default null)
returns void
language plpgsql
security definer
set search_path = pg_catalog, private
as $$
begin
  update private.account_email_outbox
  set sent_at = case when delivered then now() else sent_at end,
      claimed_at = null,
      last_error = case when delivered then null else left(coalesce(failure, 'delivery failed'), 500) end
  where id = message_id;
end;
$$;

revoke all on function public.claim_account_email_outbox(integer) from public, anon, authenticated;
revoke all on function public.finish_account_email_outbox(bigint, boolean, text) from public, anon, authenticated;
grant execute on function public.claim_account_email_outbox(integer) to service_role;
grant execute on function public.finish_account_email_outbox(bigint, boolean, text) to service_role;
