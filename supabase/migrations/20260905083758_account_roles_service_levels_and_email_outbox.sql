drop function if exists public.admin_list_account_access();
create function public.admin_list_account_access(
  search_text text default '',
  status_filter text default 'all',
  role_filter text default 'all',
  service_filter text default 'all',
  page_size integer default 50,
  page_offset integer default 0
)
returns table(
  user_id uuid,
  email text,
  status text,
  service_level text,
  admin_role text,
  requested_at timestamptz,
  reviewed_at timestamptz,
  total_count bigint
)
language plpgsql
stable
security definer
set search_path = pg_catalog, auth, public
as $$
declare
  normalized_search text := lower(trim(coalesce(search_text, '')));
  safe_limit integer := least(greatest(coalesce(page_size, 50), 1), 100);
  safe_offset integer := greatest(coalesce(page_offset, 0), 0);
begin
  if not public.is_app_admin() then
    raise exception 'admin required' using errcode = '42501';
  end if;
  if status_filter not in ('all', 'pending', 'approved', 'rejected')
    or role_filter not in ('all', 'owner', 'co_admin', 'member')
    or service_filter not in ('all', 'full', 'timetable_only') then
    raise exception 'invalid account filter' using errcode = '22023';
  end if;

  return query
  with filtered as (
    select
      access.user_id,
      users.email::text as email,
      access.status::text as status,
      access.service_level::text as service_level,
      admin.admin_role::text as admin_role,
      access.requested_at,
      access.reviewed_at
    from public.account_access access
    join auth.users users on users.id = access.user_id
    left join public.app_admins admin on admin.user_id = access.user_id and admin.revoked_at is null
    where (normalized_search = '' or lower(users.email::text) like '%' || normalized_search || '%')
      and (status_filter = 'all' or access.status = status_filter)
      and (service_filter = 'all' or access.service_level = service_filter)
      and (role_filter = 'all'
        or (role_filter = 'member' and admin.user_id is null)
        or admin.admin_role = role_filter)
  )
  select filtered.*, count(*) over ()
  from filtered
  order by
    case filtered.status when 'pending' then 0 when 'approved' then 1 else 2 end,
    filtered.requested_at desc,
    filtered.user_id
  limit safe_limit offset safe_offset;
end;
$$;

revoke all on function public.admin_list_account_access(text, text, text, text, integer, integer) from public, anon;
grant execute on function public.admin_list_account_access(text, text, text, text, integer, integer) to authenticated;

create or replace function public.admin_update_account(
  target_user_id uuid,
  next_status text,
  next_service_level text
)
returns void
language plpgsql
security definer
set search_path = pg_catalog, auth, public, private
as $$
declare
  actor uuid := auth.uid();
  target_email text;
  previous_service text;
begin
  if not public.is_app_admin() then
    raise exception 'admin required' using errcode = '42501';
  end if;
  if target_user_id is null or target_user_id = actor then
    raise exception 'cannot review own account' using errcode = '22023';
  end if;
  if exists (select 1 from public.app_admins where user_id = target_user_id and revoked_at is null) then
    raise exception 'administrator role must be removed first' using errcode = '42501';
  end if;
  if next_status not in ('approved', 'rejected')
    or next_service_level not in ('full', 'timetable_only') then
    raise exception 'invalid access update' using errcode = '22023';
  end if;

  select users.email::text, access.service_level
    into target_email, previous_service
  from auth.users users
  join public.account_access access on access.user_id = users.id
  where users.id = target_user_id;
  if target_email is null then
    raise exception 'account not found' using errcode = 'P0002';
  end if;

  update public.account_access
  set status = next_status,
      service_level = next_service_level,
      reviewed_at = now(),
      reviewed_by = actor
  where user_id = target_user_id;

  insert into public.admin_audit_log (actor_id, action, target_user_id, target_email)
  values (actor,
    case
      when next_status = 'approved' and previous_service is distinct from next_service_level then 'service_changed'
      when next_status = 'approved' then 'account_approved'
      else 'account_rejected'
    end,
    target_user_id,
    target_email
  );

  perform private.queue_account_email(
    'access:' || target_user_id::text || ':' || txid_current()::text,
    target_email,
    case
      when next_status = 'rejected' then 'access_rejected'
      when previous_service is distinct from next_service_level then 'service_changed'
      else 'access_approved'
    end,
    jsonb_build_object('service_level', next_service_level)
  );
end;
$$;

revoke all on function public.admin_update_account(uuid, text, text) from public, anon;
grant execute on function public.admin_update_account(uuid, text, text) to authenticated;

create or replace function public.owner_set_admin_role(target_user_id uuid, next_role text)
returns void
language plpgsql
security definer
set search_path = pg_catalog, auth, public, private
as $$
declare
  actor uuid := auth.uid();
  target_email text;
begin
  if not public.is_app_owner() then
    raise exception 'owner required' using errcode = '42501';
  end if;
  if target_user_id is null or target_user_id = actor then
    raise exception 'cannot change own owner role' using errcode = '22023';
  end if;
  if next_role not in ('co_admin', 'none') then
    raise exception 'invalid administrator role' using errcode = '22023';
  end if;

  select users.email::text into target_email from auth.users users where users.id = target_user_id;
  if target_email is null then
    raise exception 'account not found' using errcode = 'P0002';
  end if;

  if next_role = 'co_admin' then
    if not exists (
      select 1 from public.account_access
      where user_id = target_user_id and status = 'approved'
    ) then
      raise exception 'account must be approved first' using errcode = '22023';
    end if;
    insert into public.app_admins (user_id, admin_role, created_by, revoked_at)
    values (target_user_id, 'co_admin', actor, null)
    on conflict (user_id) do update
      set admin_role = 'co_admin', created_by = actor, revoked_at = null;
    update public.account_access set service_level = 'full' where user_id = target_user_id;
  else
    update public.app_admins
    set revoked_at = now()
    where user_id = target_user_id and admin_role = 'co_admin' and revoked_at is null;
    if not found then
      raise exception 'active co-admin not found' using errcode = 'P0002';
    end if;
  end if;

  insert into public.admin_audit_log (actor_id, action, target_user_id, target_email)
  values (actor, case when next_role = 'co_admin' then 'coadmin_granted' else 'coadmin_revoked' end, target_user_id, target_email);
  perform private.queue_account_email(
    'admin-role:' || target_user_id::text || ':' || txid_current()::text,
    target_email,
    case when next_role = 'co_admin' then 'coadmin_granted' else 'coadmin_revoked' end,
    '{}'::jsonb
  );
end;
$$;

revoke all on function public.owner_set_admin_role(uuid, text) from public, anon;
grant execute on function public.owner_set_admin_role(uuid, text) to authenticated;

create or replace function public.request_account_access()
returns text
language plpgsql
security definer
set search_path = pg_catalog, auth, public, private
as $$
declare
  actor uuid := auth.uid();
  actor_email text;
  current_status text;
  event_id text;
  admin_row record;
begin
  if actor is null then
    raise exception 'authenticated user required' using errcode = '28000';
  end if;
  select users.email::text, access.status
    into actor_email, current_status
  from auth.users users
  left join public.account_access access on access.user_id = users.id
  where users.id = actor;

  if current_status = 'approved' then return 'approved'; end if;
  if current_status = 'pending' then return 'pending'; end if;

  insert into public.account_access (user_id, status, requested_at, last_reapplied_at)
  values (actor, 'pending', now(), now())
  on conflict (user_id) do update
    set status = 'pending', requested_at = now(), last_reapplied_at = now(), reviewed_at = null, reviewed_by = null;

  insert into public.admin_audit_log (actor_id, action, target_user_id, target_email)
  values (actor, 'access_reapplied', actor, actor_email);

  event_id := 'reapply:' || actor::text || ':' || txid_current()::text;
  for admin_row in
    select users.email::text as email
    from public.app_admins admin
    join auth.users users on users.id = admin.user_id
    where admin.revoked_at is null and users.email is not null
  loop
    perform private.queue_account_email(event_id || ':' || md5(admin_row.email), admin_row.email, 'access_reapplied', jsonb_build_object('applicant_email', actor_email));
  end loop;
  return 'pending';
end;
$$;

revoke all on function public.request_account_access() from public, anon;
grant execute on function public.request_account_access() to authenticated;

create or replace function public.create_pending_account_access()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, auth, public, private
as $$
declare admin_row record;
begin
  insert into public.account_access (user_id, status)
  values (new.id, 'pending')
  on conflict (user_id) do nothing;
  for admin_row in
    select users.email::text as email
    from public.app_admins admin
    join auth.users users on users.id = admin.user_id
    where admin.revoked_at is null and users.email is not null
  loop
    perform private.queue_account_email(
      'registration:' || new.id::text || ':' || md5(admin_row.email),
      admin_row.email,
      'registration_notice',
      jsonb_build_object('applicant_email', new.email)
    );
  end loop;
  return new;
end;
$$;

